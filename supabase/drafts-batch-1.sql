## Your thumb is running on autopilot

Your brain loves to automate anything you do often. The first few times you open an app, you're making a choice. After hundreds of repetitions, it becomes a **motor habit**, closer to typing your password than to making a decision.

Habit researchers describe the loop as:

- **Cue**: a moment of boredom, waiting in line, a pause in work, picking up the phone
- **Routine**: tap the app
- **Reward**: a hit of something new, funny or interesting

Repeat that loop enough and the cue alone triggers the routine. You're mid-scroll before your conscious mind has caught up.

## Why social apps are especially sticky

Feeds use **variable rewards**. Most posts are forgettable, but every so often one is great, and you never know which swipe will deliver it. That unpredictability is exactly what makes a behaviour hard to stop. It's the same principle that makes slot machines compelling.

Add infinite scroll and autoplay, and there's never a natural moment to stop. The default is always *keep going*.

## How to break the automatic tap

### Move the app

Your thumb has memorised where the app lives. Move it to a different screen, or into a folder, or off the home screen entirely. For the first few days you'll tap empty space, and that moment of surprise is the habit breaking.

### Add a pause before it opens

The key is to put a speed bump between the reflex and the feed. Even a few seconds of friction turns an automatic action back into a decision. Apps built on iPhone's Screen Time features can shield chosen apps so they don't open straight away.

### Notice the cue, not just the habit

Next time you catch yourself in the app, ask: *what was I doing just before?* Bored? Avoiding a task? Waiting? Most people find two or three cues account for most of their sessions. Once you know your cues, you can plan for them.

