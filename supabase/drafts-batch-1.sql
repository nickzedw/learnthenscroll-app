$lts$In 1984, psychologist Robert Cialdini published *Influence: The Psychology of Persuasion*, a book built on years of studying how salespeople, marketers and fundraisers get people to say yes. He boiled it down to six principles. Once you know them, you'll spot them everywhere, including in the apps on your phone.

## 1. Reciprocity

We feel obliged to give back when someone gives to us first.

**Example:** a free sample at the supermarket, or a restaurant leaving mints with the bill. Small, unexpected gifts make people more inclined to return the favour.

## 2. Commitment and consistency

Once we commit to something, especially publicly or in writing, we like to stay consistent with it.

**Example:** a small first step ("just sign up for the free trial") makes the bigger step later feel natural. It's also why writing your goals down works.

## 3. Social proof

When we're unsure, we look at what other people are doing.

**Example:** reviews, star ratings, "bestseller" labels and "1,000 people bought this today". The more uncertain the situation, the more powerful social proof becomes.

## 4. Authority

We tend to follow people who seem credible or expert.

